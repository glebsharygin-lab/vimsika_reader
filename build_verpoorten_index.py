"""Build page locators for Viṃśikā terms in Verpoorten's official 2025 PDF.

Pass the publisher PDF locally. The generated asset carries headwords and
page numbers for the Reader's vocabulary. Definitions stay in the source PDF.
"""
import argparse
from collections import defaultdict
from hashlib import sha256
import json
from pathlib import Path
import re
import subprocess
import unicodedata

import pdfplumber
from pdfplumber.utils import cluster_objects, extract_text

SITE = Path(__file__).resolve().parents[1]
PDF_URL = (
    "https://histoire.unistra.fr/websites/histoire/Departements_instituts/"
    "histoire-religions/Publications_PDF/PIHR_HS1_2025_Verpoorten.pdf"
)
PDF_SHA256 = "dbb7c185a67d98aa1a6c264ea35dd9a1a20634be6a37e027229cc0ec87a362c8"
VOCABULARY_SCRIPT = """
const fs = require("node:fs");
const vm = require("node:vm");
const context = {window: {}};
for (const name of ["corpus", "lexicon", "lexicon-corpus"]) {
  vm.runInNewContext(fs.readFileSync(name + ".js", "utf8"), context);
}
const { CORPUS_DATA, VIMSIKA_LEXICON, VIMSIKA_CORPUS_LEXICON } = context.window;
const sanskrit = CORPUS_DATA.sources.filter(source => source.languageCode === "san");
const forms = new Set();
for (const passage of CORPUS_DATA.passages) {
  for (const source of sanskrit) {
    const witness = passage.texts[source.id];
    for (const token of witness?.tokens || []) {
      forms.add(token.text ?? witness.text.slice(token.start, token.end));
    }
  }
}
const entries = [
  ...VIMSIKA_LEXICON.entries, ...VIMSIKA_CORPUS_LEXICON.entries,
  ...(CORPUS_DATA.lexiconEntries || []),
];
for (const entry of entries) {
  if ((entry.language || "san") !== "san") continue;
  for (const term of [entry.lemma, ...(entry.forms || [])]) {
    if (term) forms.add(term);
  }
}
console.log(JSON.stringify([...forms]));
"""


def key(text):
    form = unicodedata.normalize("NFC", text.strip().lower()).replace("ṁ", "ṃ")
    return re.sub(r"[\s\-‐‑√]", "", form)


def headings(page):
    # Body lines start 7pt to the right of the heading in each column.
    body = [char for char in page.chars if 40 < char["top"] < 761]
    for margin, stop in [(56.7, 300), (315.7, 552)]:
        column = [char for char in body if margin - 0.5 < char["x0"] < stop]
        for line in cluster_objects(column, "top", 2):
            first = min((char["x0"] for char in line if char["text"].strip()), default=stop)
            if abs(first - margin) > 0.5:
                continue
            heading = extract_text(line, x_tolerance=1.7).strip()
            # Omit editorial cross-references and abbreviated suffix groups.
            lemma = re.split(r"[/,;]|\s+\(", heading, maxsplit=1)[0].strip()
            if lemma.isupper() and re.fullmatch(r"[A-ZĀĪŪṚṜḶḸṄÑṬḌṆŚṢṂṀḤ√‐‑ -]+", lemma):
                yield unicodedata.normalize("NFC", lemma.lower())


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("pdf", type=Path)
    parser.add_argument("--output", type=Path, default=SITE / "verpoorten-index.js")
    args = parser.parse_args()
    if sha256(args.pdf.read_bytes()).hexdigest() != PDF_SHA256:
        parser.error("Expected the publisher's 2025 PDF at " + PDF_URL)

    result = subprocess.run(
        ["node", "-e", VOCABULARY_SCRIPT], cwd=SITE, check=True,
        capture_output=True, encoding="utf-8",
    )
    vocabulary = {key(term) for term in json.loads(result.stdout) if isinstance(term, str)}
    locations = defaultdict(set)
    with pdfplumber.open(args.pdf) as pdf:
        for number in range(44, 757):
            page = pdf.pages[number - 1]
            for term in headings(page):
                if key(term) in vocabulary:
                    locations[term].add(number)
            page.close()

    index = [[term, sorted(locations[term])] for term in sorted(locations)]
    args.output.write_text(
        "// Generated by scripts/build_verpoorten_index.py.\n"
        "window.VIMSIKA_VERPOORTEN_INDEX = " + json.dumps(index, ensure_ascii=False) + ";\n",
        encoding="utf-8", newline="\n",
    )
    print(f"Indexed {len(index)} corpus terms at {sum(len(pages) for _, pages in index)} PDF locations.")


if __name__ == "__main__":
    main()
